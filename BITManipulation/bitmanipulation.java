package BITManipulation;

public class bitmanipulation {
    public static void main(String args[]){
        System.out.println(5 & 6);
        System.out.println(5 | 6);
        System.out.println(5 ^ 6);
        System.out.println(~5+" ans");
        System.out.println(5<<2);
        System.out.println(5>>2);
        System.out.println(6>>1);
        System.out.println(2>>1);

    } 
    
}
